// gen-resume.mjs: writes the parts of the resume that come from content/profile.json
// (Leadership & Design, Skills, Certificates and recognition) into resume/generated/.
// Run automatically by scripts/build-resume.sh and by the deploy workflow.
// The project and research bullets stay hand-written in resume/bank/ on purpose,
// because you tailor those per company.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const root = new URL("../", import.meta.url);
const data = JSON.parse(readFileSync(new URL("content/profile.json", root), "utf8"));
const out = new URL("resume/generated/", root);
mkdirSync(out, { recursive: true });

// Escape the characters LaTeX treats specially.
const tex = (s) => String(s)
  .replace(/\\/g, "\\textbackslash{}")
  .replace(/([&%$#_{}])/g, "\\$1")
  .replace(/~/g, "\\textasciitilde{}")
  .replace(/\^/g, "\\textasciicircum{}");
const items = (list) => list.map((b) => `\\item ${tex(b.text)}`).join("\n");
const header = "% GENERATED by scripts/gen-resume.mjs from content/profile.json. Do not edit; edit the JSON.\n";

// Leadership & Design
const L = data.leadership;
let lead = header;
if (L && L.items?.length) {
  lead += `\\section{${tex(L.title)}}\n`;
  for (const it of L.items) {
    lead += `\\entry{${tex(it.org)}}{${tex(it.period)}}\n\\entrysub{${tex(it.role)}}{}\n`;
    lead += `\\begin{resumeitems}\n${items(it.bullets)}\n\\end{resumeitems}\n`;
  }
}
writeFileSync(new URL("leadership.tex", out), lead);

// Skills
let skills = header + "\\Needspace{13\\baselineskip}\n\\section{Skills}\n";
for (const r of data.resume.skillRows) skills += `\\skillrow{${tex(r.label)}}{${r.items.map((i) => `\\pill{${tex(i)}}`).join("")}}\n`;
const id = data.identity;
skills += `\\skillrow{Spoken languages}{${id.languagesSpoken.map((i) => `\\pill{${tex(i)}}`).join("")}`;
if (id.hobbies?.length) skills += `\\hspace{1.2em}{\\color{teal}\\bfseries Hobbies\\ }${id.hobbies.map((i) => `\\pill{${tex(i)}}`).join("")}`;
skills += "}\n";
writeFileSync(new URL("skills.tex", out), skills);

// Certificates and recognition: two compact columns (certificates left, letters right)
const line = (c) => {
  const label = c.kind === "appreciation" && c.title.includes(c.issuer) ? c.title : `${c.title}, ${c.issuer}`;
  return `${tex(label)}${c.date ? `\\ {\\small\\color{soft}${tex(c.date)}}` : ""}`;
};
const certsOnly = data.certifications.filter((c) => c.kind !== "appreciation");
const letters = data.certifications.filter((c) => c.kind === "appreciation");
const col = (list) => list.map((c) => `\\noindent ${line(c)}\\par`).join("\n");
let certs = header + "\\Needspace{4\\baselineskip}\n\\section{Certificates and Recognition}\n";
certs += `\\noindent\\begin{minipage}[t]{0.49\\linewidth}\n${col(certsOnly)}\n\\par{\\small\\color{soft}Documents at \\vurl{${id.site}}{${tex(id.site.replace(/^https:\/\//, "").replace(/\/$/, ""))}}}\n\\end{minipage}\\hfill\n`;
certs += `\\begin{minipage}[t]{0.49\\linewidth}\n${col(letters)}\n\\end{minipage}\\par\n`;
writeFileSync(new URL("certificates.tex", out), certs);
console.log("resume/generated/ written");
